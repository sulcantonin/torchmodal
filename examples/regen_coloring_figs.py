def get_clean_trajectory():
    """Pick a graph whose seed-0 MLNN solve reaches a *proper crisp* colouring,
    so the last panel shows zero violations. Try medium graphs first, then fall
    back to the smaller/easier tier (cleaner to draw, reliably solved)."""
    for n, p, lo in [(20, 0.35, 1000), (12, 0.30, 2000)]:
        for seed in range(lo, lo + 45):
            A, _ = gc.generate_graph(n, 3, p, seed=seed)
            _, snaps = gc.solve_mlnn(A, 3, capture=True)
            if snaps and gc.is_proper(A, snaps[-1][2]):   # final CRISP colouring proper
                return A, snaps
    return A, snaps                                       # fall back to last tried


JSON_OUT = Path(__file__).resolve().parent / "coloring_solve.json"
TEX_OUT = PAPER_I / "coloring_solve.tex"
NODE_COLOR = {0: "mlblue", 1: "mlamber", 2: "mlgreen"}     # unified palette


def emit_solve(A, snaps):
    """compute -> JSON (positions, edges, per-epoch colours) -> pure-TikZ .tex."""
    G = nx.from_numpy_array(A)
    try:
        pos = nx.kamada_kawai_layout(G)
    except Exception:
        pos = nx.spring_layout(G, seed=0)
    edges = [(int(u), int(v)) for u, v in G.edges()]
    elabels = ["Epoch 1", "Epoch 200", "Epoch 400", "Epoch 600"]
    epochs = []
    for i, (ep, tot, col, _per) in enumerate(snaps):
        col = np.asarray(col)
        epochs.append(dict(label=elabels[i] if i < len(elabels) else f"Epoch {int(ep)}",
                           ep=int(ep), sumLcontra=float(tot),
                           bad_edges=int(sum(1 for u, v in edges if col[u] == col[v])),
                           col=[int(c) for c in col]))
    data = {"n_nodes": int(G.number_of_nodes()),
            "pos": {int(k): [float(v[0]), float(v[1])] for k, v in pos.items()},
            "edges": edges, "epochs": epochs}
    JSON_OUT.write_text(json.dumps(data, indent=2))

    SC, R = 1.55, 0.12                                      # cm/unit, node radius cm
    blocks = []
    for e in epochs:
        col = e["col"]
        L = [r"\begin{tikzpicture}[baseline=(current bounding box.north)]"]
        for (u, v) in edges:                                # edges first (under nodes)
            x1, y1 = pos[u]; x2, y2 = pos[v]
            sty = ("mlred,line width=1.4pt" if col[u] == col[v]
                   else "mlgray!55,line width=0.4pt")
            L.append(rf"\draw[{sty}] ({x1*SC:.2f},{y1*SC:.2f}) -- ({x2*SC:.2f},{y2*SC:.2f});")
        for nd in range(data["n_nodes"]):
            x, y = pos[nd]
            L.append(rf"\filldraw[{NODE_COLOR[col[nd] % 3]},draw=black,line width=0.3pt] "
                     rf"({x*SC:.2f},{y*SC:.2f}) circle ({R}cm);")
        L.append(r"\end{tikzpicture}")
        cap = (rf"{{\scriptsize\textbf{{{e['label']}}}\\[-1pt]"
               rf"{e['bad_edges']} mono.\ edges}}")
        blocks.append(rf"\begin{{minipage}}[t]{{0.245\linewidth}}\centering" "\n"
                      + "\n".join(L) + f"\\\\[3pt]\n{cap}\n" + r"\end{minipage}")
    body = ("%% AUTO-GENERATED by regen_coloring_figs.py from coloring_solve.json\n"
            "%% nodes = current arg-max colour (mlblue/mlamber/mlgreen); "
            "mlred edge = monochromatic (axiom violation).\n\\centering\n"
            + "\\hfill\n".join(blocks))
    TEX_OUT.write_text(body)
    return [(e["ep"], e["sumLcontra"], e["bad_edges"]) for e in epochs]


def fig_recover(learn):
    fig, axes = plt.subplots(1, 2, figsize=(6.4, 3.3))
    im = None
    for ax, M, ttl in [(axes[0], learn["A_true"], "true adjacency"),
                       (axes[1], learn["A_learned"], r"learned $A_\theta$")]:
        n = M.shape[0]
        im = ax.imshow(M, cmap="Blues", vmin=0, vmax=1)
        ax.set_title(ttl, fontsize=14, pad=8)
        ax.set_xticks(np.arange(-0.5, n, 1), minor=True)
        ax.set_yticks(np.arange(-0.5, n, 1), minor=True)
        ax.grid(which="minor", color="white", linewidth=0.7)
        ax.tick_params(which="both", length=0, labelbottom=False, labelleft=False)
        for s in ax.spines.values():
            s.set_edgecolor("#999999"); s.set_linewidth(0.5)
    cb = fig.colorbar(im, ax=axes, fraction=0.046, pad=0.04)
    cb.outline.set_linewidth(0.4)
    cb.ax.tick_params(labelsize=9, length=2)
    fig.savefig(PAPER_I / "coloring_recover.pdf")
    plt.close(fig)


